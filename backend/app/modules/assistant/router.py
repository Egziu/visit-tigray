"""Internal Bureau AI assistant.

* Works strictly inside the requesting employee's permissions: each intent maps to a permission
  and to read-only data functions. There is no write path — it cannot publish content, change
  advisories, approve prizes, move money or edit protected records.
* Facts are computed deterministically from the database. A local model (when the AI policy allows
  generation) only drafts prose around those facts; output is always labelled as a draft.
"""
from __future__ import annotations

import json
import re
from collections import Counter
from datetime import date, timedelta

from fastapi import APIRouter, Depends, Request
from pydantic import BaseModel, Field
from sqlalchemy import select
from sqlalchemy.orm import Session

from app.core.db import get_db, utcnow
from app.core.errors import AppError
from app.core.ethiopic import fold_for_search
from app.modules.audit import service as audit
from app.modules.identity.deps import require
from app.modules.identity.service import Principal
from app.modules.tie.guide import effective_mode
from app.modules.tie.models import Feedback, Message
from app.modules.tie.policy import parse_model_json
from app.modules.tie.providers import ProviderError, get_chain

router = APIRouter(prefix="/api/bureau/assistant", tags=["assistant"])

INTENTS = [
    ("freshness", "destinations.read_draft", r"(missing|outdated|stale|fresh|verify|verification|incomplete|ዘይተረጋገጸ|ያልተረጋገጠ)"),
    ("translations", "destinations.read_draft", r"(translat|ትርጉም|ትርጉማት)"),
    ("faq", "analytics.view", r"(frequent|faq|common question|most asked|ብዙሕ ዝሕተት|ተደጋጋሚ)"),
    ("feedback", "analytics.view", r"(feedback|complain|rating|satisf)"),
    ("moderation", "community.moderate", r"(moderat|report|queue|pending stor)"),
    ("draft", "bureau.assistant", r"(draft|letter|email|correspondence|brief|meeting|memo|ደብዳቤ|ደብዳቤ)"),
    ("summary", "analytics.view", r"(summar|activity|trend|analytic|report|dashboard|metric|overview|ጸብጻብ|ሪፖርት)"),
]
NOTICE = "Draft generated by the Bureau assistant from platform data. Review before use; it cannot publish or change records."


def detect_intent(q: str) -> tuple[str, str]:
    low = q.lower()
    for name, perm, pat in INTENTS:
        if re.search(pat, low):
            return name, perm
    return "summary", "analytics.view"


def faq(db: Session, days: int = 30) -> list[dict]:
    since = utcnow() - timedelta(days=days)
    qs = db.execute(select(Message.content).where(Message.role == "user", Message.created_at >= since)).scalars().all()
    counts = Counter(fold_for_search(q)[:120] for q in qs)
    return [{"question": q, "count": n} for q, n in counts.most_common(15) if n >= 2]  # aggregated, k>=2


def feedback_summary(db: Session, days: int = 30) -> dict:
    since = utcnow() - timedelta(days=days)
    rows = db.execute(select(Feedback).where(Feedback.created_at >= since)).scalars().all()
    return {"up": sum(r.rating == "up" for r in rows), "down": sum(r.rating == "down" for r in rows),
            "recent_comments": [r.comment for r in rows if r.comment][:10]}


def compute(db: Session, intent: str) -> tuple[dict, list[str]]:
    from app.modules.analytics.router import summary
    from app.modules.content.router import content_freshness
    from app.modules.content.service import missing_translations

    if intent == "freshness":
        return {"records": content_freshness(None, db)}, ["content.freshness"]
    if intent == "translations":
        return {"records": missing_translations(db)}, ["translations.missing"]
    if intent == "faq":
        return {"questions": faq(db)}, ["tie.messages (aggregated, k>=2)"]
    if intent == "feedback":
        return feedback_summary(db), ["tie.feedback"]
    if intent == "moderation":
        from app.modules.community.router import queue
        q = queue(None, db)
        return {"pending_items": len(q["items"]), "open_reports": len(q["reports"]), "open_appeals": len(q["appeals"])}, \
            ["community.moderation_queue"]
    if intent == "draft":
        return {}, []
    s = summary(db, date.today() - timedelta(days=29), date.today())
    return {k: s[k] for k in ("website_engagement", "ai", "operations", "measured_tourism", "notice")}, ["analytics.summary"]


def deterministic_text(intent: str, data: dict) -> str:
    if intent == "freshness":
        recs = data["records"]
        lines = [f"{len(recs)} destination records need attention:"]
        lines += [f"• {r['slug']}: {', '.join(r['reasons'])}" for r in recs[:20]]
        return "\n".join(lines)
    if intent == "translations":
        recs = data["records"]
        return "\n".join([f"{len(recs)} destinations have missing or unreviewed translations:"] +
                         [f"• {r['slug']}: missing {r['missing'] or '—'}, unreviewed {r['unreviewed'] or '—'}" for r in recs[:20]])
    if intent == "faq":
        qs = data["questions"]
        return "Most frequent guide questions (last 30 days):\n" + ("\n".join(f"• ({q['count']}) {q['question']}" for q in qs)
                                                                    or "Not enough repeated questions yet.")
    if intent == "feedback":
        return f"Guide feedback (30 days): {data['up']} positive, {data['down']} negative."
    if intent == "moderation":
        return (f"Moderation: {data['pending_items']} items awaiting review, {data['open_reports']} open reports, "
                f"{data['open_appeals']} open appeals.")
    if intent == "draft":
        return ("Draft outline:\n1. Purpose\n2. Background (cite records)\n3. Key facts (verify each figure)\n"
                "4. Requested action / decision\n5. Contacts\n\n(No local language model is enabled, so only an outline is provided.)")
    we, ops = data["website_engagement"], data["operations"]
    return (f"Last 30 days — website engagement events: {sum(we['by_event_type'].values())} "
            f"({', '.join(f'{k}: {v}' for k, v in we['by_event_type'].items()) or 'none'}). "
            f"AI answers: {data['ai']['answers_by_confidence'] or 'none'}. "
            f"Pending moderation: {ops['pending_moderation']}; destinations never verified: "
            f"{ops['destinations_never_verified']} of {ops['destinations_total']}. {data['notice']}")


class AskIn(BaseModel):
    question: str = Field(min_length=3, max_length=2000)


@router.post("/ask")
def ask(body: AskIn, request: Request, p: Principal = Depends(require("bureau.assistant")), db: Session = Depends(get_db)):
    intent, perm = detect_intent(body.question)
    if not p.has(perm):
        raise AppError(403, "forbidden", f"Your role does not include access to {intent} data.", {"required": [perm]})
    data, sources = compute(db, intent)
    text = deterministic_text(intent, data)
    generated_by = "deterministic"
    chain = get_chain(effective_mode(db))
    for provider in chain:
        try:
            res = provider.chat([
                {"role": "system", "content": "You draft internal notes for Tourism Bureau staff. Use ONLY the facts in "
                 "DATA; do not add numbers. Never claim an action was taken. Reply as JSON {\"answer\": \"...\"}."},
                {"role": "user", "content": f"REQUEST: {body.question}\nDATA: {json.dumps(data, default=str)[:12000]}\n"
                 f"FACT SUMMARY: {text}"}], mode=effective_mode(db))
            draft = str(parse_model_json(res.text).get("answer", "")).strip()
            if draft:
                text, generated_by = draft, f"{provider.name}:{provider.model}"
                break
        except (ProviderError, ValueError, Exception):  # noqa: BLE001 - fall back to deterministic text
            continue
    audit.record(db, action="assistant.ask", resource_type="assistant", resource_id=intent, actor=p, request=request)
    db.commit()
    return {"intent": intent, "answer": text, "data": data, "sources": sources, "draft": True,
            "generated_by": generated_by, "notice": NOTICE}
